"""
Event-driven folder watcher and pipeline coordinator for DropSort / DockShelf.
"""

from __future__ import annotations

import logging
import queue
import threading
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from typing import Any

from watchdog.events import FileSystemEvent, FileSystemEventHandler
from watchdog.observers import Observer

from .config import ThreadSafeRulesManager
from .history import HistoryManager
from .mover import safe_move
from .rules import destination_for
from .stability import wait_until_stable

logger = logging.getLogger(__name__)


class FolderWatchHandler(FileSystemEventHandler):
    """
    Watchdog event handler filtering for top-level file creations and renames.

    OS Concepts applied:
    - OS Event-driven I/O: Catches asynchronous filesystem events generated by the kernel
      (ReadDirectoryChangesW on Windows) without wasteful CPU polling.
    - Scope Isolation: Filters events to strictly process files directly in the watched root,
      ignoring directory mutations and recursion into sorted subfolders.
    """

    def __init__(self, watcher: FolderWatcher) -> None:
        super().__init__()
        self.watcher = watcher

    def on_created(self, event: FileSystemEvent) -> None:
        if event.is_directory:
            return
        self.watcher.handle_incoming_file(Path(event.src_path))

    def on_moved(self, event: Any) -> None:
        # Browser downloads typically write to a temporary file (.crdownload/.tmp)
        # and then rename the finished file. We catch the dest_path rename event.
        if event.is_directory:
            return
        dest_path = getattr(event, "dest_path", None)
        if dest_path:
            self.watcher.handle_incoming_file(Path(dest_path))


class FolderWatcher:
    """
    Coordinates the background watching, stability checking, moving, and history recording pipeline.

    OS Concepts applied:
    - Multithreading & Thread Pools: Offloads blocking file stability checks and I/O operations
      to a bounded worker pool (ThreadPoolExecutor, max 4 workers) so event listening remains non-blocking.
    - Thread Synchronization & Message Queues: Passes result notifications to the UI thread via
      a thread-safe queue.Queue, avoiding Tkinter thread-safety violations.
    - Idempotency & Concurrency Guards: A lock-protected set tracks active files to prevent duplicate
      concurrent operations on the same target.
    """

    def __init__(
        self,
        watch_folder: Path | str,
        rules_manager: ThreadSafeRulesManager,
        history_manager: HistoryManager,
        event_queue: queue.Queue | None = None,
        max_workers: int = 4,
        stability_interval: float = 0.5,
        stability_checks: int = 3,
        stability_timeout: float = 300.0,
    ) -> None:
        self.watch_folder = Path(watch_folder).resolve()
        self.rules_manager = rules_manager
        self.history_manager = history_manager
        self.event_queue = event_queue or queue.Queue()

        self.max_workers = max_workers
        self.stability_interval = stability_interval
        self.stability_checks = stability_checks
        self.stability_timeout = stability_timeout

        self._observer: Observer | None = None
        self._executor: ThreadPoolExecutor | None = None
        self._processing: set[Path] = set()
        self._lock = threading.Lock()
        self._is_running = False

    @property
    def is_running(self) -> bool:
        return self._is_running

    def set_watch_folder(self, new_folder: Path | str) -> None:
        """Dynamically update the watched folder, restarting the observer if currently running."""
        was_running = self._is_running
        if was_running:
            self.stop()
        self.watch_folder = Path(new_folder).resolve()
        self.watch_folder.mkdir(parents=True, exist_ok=True)
        if was_running:
            self.start()

    def start(self) -> None:
        """Starts the watchdog observer and thread pool executor."""
        with self._lock:
            if self._is_running:
                return

            self.watch_folder.mkdir(parents=True, exist_ok=True)
            self._executor = ThreadPoolExecutor(max_workers=self.max_workers, thread_name_prefix="WatcherWorker")

            self._observer = Observer()
            handler = FolderWatchHandler(self)
            # recursive=False ensures we only listen directly to the watched root
            self._observer.schedule(handler, str(self.watch_folder), recursive=False)
            self._observer.start()

            self._is_running = True
            logger.info("Watcher started on %s", self.watch_folder)
            self.event_queue.put({"type": "status", "status": "Watching"})

    def stop(self) -> None:
        """Shuts down the observer and drains the executor cleanly."""
        with self._lock:
            if not self._is_running:
                return
            self._is_running = False

        if self._observer:
            self._observer.stop()
            self._observer.join()
            self._observer = None

        if self._executor:
            self._executor.shutdown(wait=True)
            self._executor = None

        logger.info("Watcher stopped cleanly.")
        self.event_queue.put({"type": "status", "status": "Stopped"})

    def handle_incoming_file(self, file_path: Path) -> None:
        """Validates that the file is top-level and submits it to the worker pool with duplicate suppression."""
        try:
            resolved_path = file_path.resolve()
        except Exception:
            resolved_path = file_path

        # Must be directly in the watched folder (not in a subfolder)
        if resolved_path.parent != self.watch_folder:
            return

        with self._lock:
            # Idempotency guard: if file is already being processed by worker, drop duplicate event
            if resolved_path in self._processing:
                return
            self._processing.add(resolved_path)

        if self._executor and not self._executor._shutdown:
            self._executor.submit(self._process_pipeline, resolved_path)
        else:
            with self._lock:
                self._processing.discard(resolved_path)

    def _process_pipeline(self, file_path: Path) -> None:
        """Runs the stability check, rule lookup, two-phase safe move, and history record with retries."""
        move_id: int | None = None
        try:
            # Guard against stale events for files that were already moved or removed
            if not file_path.exists():
                return

            rules = self.rules_manager.get_rules()

            # 1. Skip if extension is ignored
            dest_subfolder = destination_for(file_path.name, rules)
            if dest_subfolder is None:
                logger.debug("File %s matches ignore extensions. Skipping.", file_path.name)
                return

            # 2. Wait until file is stable (configurable from rules.json)
            st_interval = rules.get("stability_interval", self.stability_interval)
            st_checks = rules.get("stability_checks", self.stability_checks)

            stable = wait_until_stable(
                file_path,
                interval=st_interval,
                stable_checks=st_checks,
                timeout=self.stability_timeout,
            )
            if not stable or not file_path.exists():
                logger.info("File %s was not stable or removed. Skipping.", file_path.name)
                return

            # Re-read rules in case rules updated while waiting for stability
            rules = self.rules_manager.get_rules()
            dest_subfolder = destination_for(file_path.name, rules)
            if dest_subfolder is None:
                return

            dest_dir = self.watch_folder / dest_subfolder
            dest_dir.mkdir(parents=True, exist_ok=True)
            expected_dest = dest_dir / file_path.name

            # 3. Two-Phase Commit Step 1: Write history row as 'pending' BEFORE file I/O begins
            move_id = self.history_manager.record_pending_move(file_path, expected_dest)

            # 4. Safe move with retry logic (up to 3 attempts with capped backoff so demo never feels stuck)
            max_retries = 3
            final_path = None
            last_err = None
            for attempt in range(1, max_retries + 1):
                try:
                    final_path = safe_move(file_path, dest_dir)
                    break
                except (PermissionError, OSError) as exc:
                    last_err = exc
                    if attempt < max_retries:
                        time.sleep(min(0.25 * attempt, 1.0))

            if final_path is None:
                # Retries exhausted: mark history row as 'failed', leave file untouched in folder
                logger.error("Failed to move %s after %s retries: %s", file_path.name, max_retries, last_err)
                if move_id is not None:
                    self.history_manager.fail_move(move_id, note=str(last_err))
                self.event_queue.put(
                    {
                        "type": "error",
                        "name": file_path.name,
                        "message": f"File in use or permission denied (retried 3 times): {last_err}",
                    }
                )
                return

            with self._lock:
                self._processing.discard(file_path)

            # 5. Two-Phase Commit Step 2: Mark history row as 'moved'
            self.history_manager.confirm_move(move_id, final_path)

            # 6. Push event to UI queue
            self.event_queue.put(
                {
                    "type": "moved",
                    "id": move_id,
                    "name": final_path.name,
                    "from": file_path.name,
                    "to": f"{dest_subfolder}/{final_path.name}",
                }
            )

        except Exception as exc:
            logger.exception("Unexpected error processing file %s: %s", file_path, exc)
            if move_id is not None:
                try:
                    self.history_manager.fail_move(move_id, note=str(exc))
                except Exception:
                    pass
            self.event_queue.put({"type": "error", "name": file_path.name, "message": str(exc)})
        finally:
            with self._lock:
                self._processing.discard(file_path)

    def organize_existing(self) -> int:
        """
        Scans top-level items currently in the watched folder and submits eligible files to the pipeline.

        Returns:
            Number of candidate files queued for sorting.
        """
        if not self.watch_folder.exists():
            return 0

        count = 0
        for entry in self.watch_folder.iterdir():
            if entry.is_file():
                self.handle_incoming_file(entry)
                count += 1
        return count
